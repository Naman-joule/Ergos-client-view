-- ergOS client view: reporting database schema (PostgreSQL 15+ / Supabase).
--
-- Two kinds of tables:
--   * App-owned  : identity primary keys, updated_at triggers. Written by the app or admins.
--   * Synced     : plain integer/bigint primary keys holding the ergOS ids, so foreign keys
--                  survive the copy. Written only by the sync job (as table owner). Never by the app.

BEGIN;

-- ---------------------------------------------------------------------------
-- helpers
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Tenancy (synced)
-- ---------------------------------------------------------------------------
CREATE TABLE client (
  client_id           integer PRIMARY KEY,
  name                varchar(200) NOT NULL UNIQUE,
  email               varchar(100) NOT NULL UNIQUE,
  key_contact_person  varchar(200),
  contact_number      varchar(20),
  logo_url            varchar(500),
  alias_name          varchar(100),
  is_active           boolean,
  created_at          timestamptz DEFAULT now(),
  updated_at          timestamptz DEFAULT now()
);

CREATE TABLE plant_type (
  id           integer PRIMARY KEY,
  type         varchar(50),          -- consumer / generator
  sub_type     varchar(50),          -- cement, solar, flexi_packaging, ...
  description  varchar(200)
);

CREATE TABLE plant (
  plant_id                 integer PRIMARY KEY,
  client_id                integer REFERENCES client (client_id),
  plant_type_id            integer REFERENCES plant_type (id),
  name                     varchar(200) UNIQUE,
  state                    varchar(100) NOT NULL,
  discom                   varchar(100),
  connected_load           double precision,          -- MW
  voltage_level            varchar(50),               -- 33_kv, 66_kv, 132_kv
  category_code            varchar(50),
  category_name            varchar(100),
  ct_pt_ratio              varchar(20),
  energy_multiplier        double precision DEFAULT 1.0,
  iex_contract_limit_kwh   double precision,
  is_auto_trading_enabled  boolean DEFAULT false,
  is_active                boolean DEFAULT true,
  created_at               timestamptz DEFAULT now(),
  updated_at               timestamptz DEFAULT now()
);
CREATE INDEX plant_client_id_idx ON plant (client_id);

-- ---------------------------------------------------------------------------
-- RBAC (app-owned)
-- ---------------------------------------------------------------------------
CREATE TABLE role (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(50) NOT NULL UNIQUE,     -- admin, manager, client_user
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE permission (
  permission_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  permission_name  varchar(200) NOT NULL UNIQUE,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE role_permission (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id        integer NOT NULL REFERENCES role (id),
  permission_id  integer NOT NULL REFERENCES permission (permission_id),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (role_id, permission_id)
);

CREATE TABLE "user" (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          varchar(100) NOT NULL UNIQUE,
  name           varchar(100) NOT NULL,
  password_hash  varchar(255) NOT NULL,            -- bcrypt
  role_id        integer REFERENCES role (id),
  is_active      boolean DEFAULT true,
  last_reset     timestamptz,
  created_by     integer REFERENCES "user" (id),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX user_email_lower_idx ON "user" (lower(email));

CREATE TABLE user_client_map (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
  client_id   integer NOT NULL REFERENCES client (client_id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, client_id)
);

CREATE TABLE user_plant_map (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
  plant_id    integer NOT NULL REFERENCES plant (plant_id),
  user_role   varchar(50) NOT NULL DEFAULT 'viewer',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, plant_id)
);

-- ---------------------------------------------------------------------------
-- Lookups and plant configuration (synced)
-- ---------------------------------------------------------------------------
CREATE TABLE markets (
  id    integer PRIMARY KEY,
  name  varchar(50)                -- IEX, PXIL
);

CREATE TABLE market_types (
  id           integer PRIMARY KEY,
  market_id    integer REFERENCES markets (id),
  name         varchar(50),        -- DAM, GDAM, RTM
  start_time   time,
  end_time     time,
  result_time  time
);

CREATE TABLE plant_gen_con_mapping (
  id                  integer PRIMARY KEY,
  source_plant_id     integer REFERENCES plant (plant_id),   -- the solar generator
  target_plant_id     integer REFERENCES plant (plant_id),   -- the consumer
  s_t_ratio           double precision NOT NULL,
  source_capacity     double precision,
  target_capacity     double precision,
  is_active           boolean,
  is_banking_enabled  boolean,
  created_at          timestamptz DEFAULT now(),
  updated_at          timestamptz DEFAULT now(),
  UNIQUE (source_plant_id, target_plant_id)
);

CREATE TABLE plant_open_access_charges (
  id                         integer PRIMARY KEY,
  plant_id                   integer REFERENCES plant (plant_id),
  portfolio_id               varchar(64) NOT NULL,
  effective_from             date NOT NULL,
  effective_to               date,
  distribution_loss_pct      numeric DEFAULT 3.0,
  ctu_loss_pct               numeric DEFAULT 3.95,
  stu_loss_pct               numeric DEFAULT 3.18,
  css_rate_per_kwh           numeric DEFAULT 0.49,
  electricity_duty_pct       numeric DEFAULT 7.5,
  ctu_rate_per_mwh           numeric,
  stu_rate_per_mwh           numeric,
  distribution_rate_per_mwh  numeric,
  sldc_charge                numeric,
  fees_rate_per_mwh          numeric,
  igst_pct                   numeric DEFAULT 18.0,
  nldc_app_fee               numeric,
  created_at                 timestamptz DEFAULT now(),
  updated_at                 timestamptz DEFAULT now(),
  UNIQUE (portfolio_id, effective_from)
);

CREATE TABLE state_grid_discom_tariff (
  id               integer PRIMARY KEY,
  plant_id         integer NOT NULL REFERENCES plant (plant_id),
  country          varchar(100) NOT NULL,
  state            varchar(100) NOT NULL,
  discom           varchar(100) NOT NULL,
  category_name    varchar(100) NOT NULL,
  category_code    varchar(50)  NOT NULL,
  year             integer,
  month            integer,
  block            integer CHECK (block BETWEEN 1 AND 96),
  tod_type         varchar(20),                -- PEAK / OFFPEAK / NORMAL
  tariff_33_kv     double precision,           -- ₹/kWh
  tariff_66_kv     double precision,
  tariff_132_kv    double precision,
  electricity_duty double precision,
  fppca_charge     double precision,
  created_at       timestamptz DEFAULT now(),
  updated_at       timestamptz DEFAULT now(),
  UNIQUE (plant_id, state, year, month, block, tod_type)
);

CREATE TABLE state_grid_solar_tariff (
  id          integer PRIMARY KEY,
  plant_id    integer REFERENCES plant (plant_id),
  state       varchar(100),        -- added: the original spec's unique key uses it
  year        integer,
  month       integer,
  block       integer CHECK (block BETWEEN 1 AND 96),
  tod_type    varchar(20),
  tod_price   double precision NOT NULL,
  created_at  timestamptz DEFAULT now(),
  updated_at  timestamptz DEFAULT now(),
  UNIQUE (plant_id, state, year, month, block, tod_type)
);

-- ---------------------------------------------------------------------------
-- Today page data (synced, 15-minute)
-- ---------------------------------------------------------------------------
CREATE TABLE plant_processed_meter_data (
  id               bigint PRIMARY KEY,
  plant_id         integer REFERENCES plant (plant_id),
  date             date,
  meter_timestamp  timestamptz,
  kwh              double precision,     -- cumulative register
  kwh_delta        double precision,     -- interval kWh; x4 = kW
  kvah             double precision,
  cumulative_pf    double precision,
  flags            varchar(20),          -- real / interpolated / missing
  created_at       timestamptz DEFAULT now(),
  updated_at       timestamptz DEFAULT now(),
  UNIQUE (plant_id, meter_timestamp)
);
CREATE INDEX ppmd_plant_date_idx ON plant_processed_meter_data (plant_id, date);

CREATE TABLE trading_result (
  id              integer PRIMARY KEY,
  plant_id        integer REFERENCES plant (plant_id),
  date            date,
  market_type_id  integer REFERENCES market_types (id),
  result_data     jsonb,
  created_at      timestamptz DEFAULT now(),
  updated_at      timestamptz DEFAULT now(),
  UNIQUE (plant_id, date, market_type_id)
);

CREATE TABLE trading_result_block (
  id                      bigint PRIMARY KEY,
  trading_result_id       integer REFERENCES trading_result (id) ON DELETE CASCADE,
  plant_id                integer REFERENCES plant (plant_id),
  date                    date,
  block_no                integer CHECK (block_no BETWEEN 1 AND 96),
  cleared_quantity_mw     double precision,     -- MW
  cleared_quantity        double precision,     -- kWh
  cleared_price           double precision,
  landed_cost             double precision,
  landed_cost_rs_per_kwh  double precision,
  portfolio_id            varchar(64),
  type_                   varchar(10),          -- BUY / SELL
  created_at              timestamptz DEFAULT now(),
  updated_at              timestamptz DEFAULT now(),
  UNIQUE (trading_result_id, block_no)
);
CREATE INDEX trb_plant_date_block_idx ON trading_result_block (plant_id, date, block_no);

CREATE TABLE prebid_plan (
  id                integer PRIMARY KEY,
  plant_id          integer REFERENCES plant (plant_id),
  date              date,
  market_type       varchar(20),
  exhange_name      varchar(20),          -- sic: matches ergOS
  prebid_plan_data  jsonb NOT NULL,
  created_at        timestamptz DEFAULT now(),
  updated_at        timestamptz DEFAULT now(),
  UNIQUE (date, plant_id, market_type, exhange_name)
);

CREATE TABLE banking (
  id                  integer PRIMARY KEY,
  plant_id            integer REFERENCES plant (plant_id),
  date                date,
  block               integer CHECK (block BETWEEN 1 AND 96),
  charge              double precision,
  discharge           double precision,
  adjusted_discharge  double precision,
  soc                 double precision,
  peak_balance        double precision,
  normal_balance      double precision,
  offpeak_balance     double precision,
  tod_type            varchar(20),
  created_at          timestamptz DEFAULT now(),
  updated_at          timestamptz DEFAULT now(),
  UNIQUE (date, block, plant_id)
);
CREATE INDEX banking_plant_date_idx ON banking (plant_id, date);

-- ---------------------------------------------------------------------------
-- Savings page data (synced)
-- ---------------------------------------------------------------------------
CREATE TABLE iex_tod_daily_obligation (
  id                        bigint PRIMARY KEY,
  plant_id                  integer REFERENCES plant (plant_id),   -- nullable
  portfolio_id              varchar(64) NOT NULL,
  trade_date                date NOT NULL,
  client_name               varchar(200),
  plant_name                varchar(200),
  volume_cleared_kwh        numeric(18,4),
  units_mwh                 numeric(18,4),
  iex_energy_charge         numeric(18,4),
  iex_total_cost            numeric(18,4),
  avg_landed_iex_tariff     numeric(18,4),
  ctu_transmission_charges  numeric(18,4),
  stu_transmission_charges  numeric(18,4),
  distribution_charges      numeric(18,4),
  nldc_application_fees     numeric(18,4),
  nldc_scheduling_buy       numeric(18,4),
  sldc_scheduling_charges   numeric(18,4),
  fees                      numeric(18,4),
  igst                      numeric(18,4),
  css                       numeric(18,4),
  grid_energy_cost          numeric(18,4),
  electricity_duty_amount   numeric(18,4),
  grid_total_cost           numeric(18,4),
  avg_grid_tariff           numeric(18,4),
  net_savings_per_day       numeric(18,4),
  percent_below_grid        numeric(8,4),
  excel_file_path           text,
  statement_docx_path       text,
  pdf_report_path           text,
  zip_bundle_path           text,
  raw_summary               jsonb,
  is_locked                 boolean DEFAULT true,
  created_at                timestamptz DEFAULT now(),
  updated_at                timestamptz DEFAULT now(),
  UNIQUE (portfolio_id, trade_date)
);
CREATE INDEX itdo_plant_date_idx ON iex_tod_daily_obligation (plant_id, trade_date);

CREATE TABLE optimization_results (
  id                           integer PRIMARY KEY,
  plant_id                     integer REFERENCES plant (plant_id),
  date                         date,
  block                        integer CHECK (block BETWEEN 1 AND 96),
  optimization_type            varchar(20),     -- day_ahead / rtm
  demand_kwh                   double precision,
  solar_kwh                    double precision,
  iex_draw_kwh                 double precision,
  grid_draw_kwh                double precision,
  iex_rs_per_kwh               double precision,
  grid_rs_per_kwh              double precision,
  solar_rs_per_kwh             double precision,
  landed_cost_iex_rs_per_kwh   double precision,
  final_cost                   double precision,
  bank_balance_total           double precision,
  created_at                   timestamptz DEFAULT now(),
  updated_at                   timestamptz DEFAULT now(),
  UNIQUE (date, block, plant_id, optimization_type)
);

-- ---------------------------------------------------------------------------
-- App-owned extras
-- ---------------------------------------------------------------------------
CREATE TABLE dashboard_config (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id   integer REFERENCES client (client_id),      -- NULL = global default
  version     integer NOT NULL,
  status      varchar(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  spec        jsonb NOT NULL,
  note        text,
  created_by  integer REFERENCES "user" (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT dashboard_config_client_version_key UNIQUE NULLS NOT DISTINCT (client_id, version)
);
CREATE UNIQUE INDEX dashboard_config_one_published_idx
  ON dashboard_config ((COALESCE(client_id, 0))) WHERE status = 'published';

CREATE TABLE sync_runs (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tier          varchar(10) NOT NULL,      -- fast / slow
  table_name    varchar(100) NOT NULL,
  window_from   date,
  started_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz,
  rows_written  bigint,
  status        varchar(10) NOT NULL CHECK (status IN ('running', 'ok', 'error', 'skipped')),
  error         text
);
CREATE INDEX sync_runs_table_started_idx ON sync_runs (table_name, started_at DESC);

-- ---------------------------------------------------------------------------
-- updated_at triggers (app-owned tables)
-- ---------------------------------------------------------------------------
CREATE TRIGGER role_updated_at            BEFORE UPDATE ON role            FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER permission_updated_at      BEFORE UPDATE ON permission      FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER role_permission_updated_at BEFORE UPDATE ON role_permission FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER user_updated_at            BEFORE UPDATE ON "user"          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER user_client_map_updated_at BEFORE UPDATE ON user_client_map FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER user_plant_map_updated_at  BEFORE UPDATE ON user_plant_map  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER dashboard_config_updated_at BEFORE UPDATE ON dashboard_config FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
