-- IEX Daily Obligation Reports (DOR) uploaded through the app, one per plant, market and delivery day.
-- The PDF itself lives on the report FTP server (OBLIGATION_FTP_URL); this table records where, and is
-- what the app checks before serving a file.
--   read:   anyone who can see the plant (same rule as every plant-scoped table)
--   write:  admins only (app_is_admin()), enforced here as well as in the app
-- The app-owned table is not touched by the ergOS sync. Safe to re-run.

SET client_min_messages = warning;
BEGIN;

CREATE TABLE IF NOT EXISTS iex_obligation_report (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plant_id        integer NOT NULL,                 -- no FK: the sync may rewrite plant rows
  market          varchar(10) NOT NULL CHECK (market IN ('DAM', 'RTM', 'GDAM', 'HP-DAM', 'TAM')),
  delivery_date   date NOT NULL,
  trading_date    date,                             -- day-ahead markets only
  portfolio_code  varchar(20),
  portfolio_name  varchar(200),
  file_path       varchar(500) NOT NULL,            -- absolute path on the FTP server
  original_name   varchar(255) NOT NULL,
  size_bytes      integer NOT NULL CHECK (size_bytes > 0),
  uploaded_by     integer NOT NULL,
  uploaded_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (plant_id, market, delivery_date)
);
CREATE INDEX IF NOT EXISTS iex_obligation_report_plant_date_idx ON iex_obligation_report (plant_id, delivery_date);

ALTER TABLE iex_obligation_report ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON iex_obligation_report TO ergos_view_app;
REVOKE DELETE, TRUNCATE ON iex_obligation_report FROM ergos_view_app;

DROP POLICY IF EXISTS app_read ON iex_obligation_report;
CREATE POLICY app_read ON iex_obligation_report FOR SELECT TO ergos_view_app
  USING (plant_id IN (SELECT app_accessible_plant_ids()));

DROP POLICY IF EXISTS app_insert ON iex_obligation_report;
CREATE POLICY app_insert ON iex_obligation_report FOR INSERT TO ergos_view_app
  WITH CHECK (app_is_admin() AND uploaded_by = app_user_id() AND plant_id IN (SELECT app_accessible_plant_ids()));

DROP POLICY IF EXISTS app_update ON iex_obligation_report;
CREATE POLICY app_update ON iex_obligation_report FOR UPDATE TO ergos_view_app
  USING (app_is_admin())
  WITH CHECK (app_is_admin() AND uploaded_by = app_user_id() AND plant_id IN (SELECT app_accessible_plant_ids()));

COMMIT;
