// postinstall: vendor the Harmony runtime and logos into public/, and generate the
// server-side icon map from harmony.js. Both outputs are gitignored.
import { createRequire } from 'node:module';
import { mkdirSync, copyFileSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// package.json isn't exported by ergos-harmony, so resolve through a file that is.
const harmonyJs = require.resolve('ergos-harmony/harmony.js');
const dsDir = dirname(harmonyJs);

const out = join(root, 'public', 'vendor', 'ergos');
mkdirSync(join(out, 'logo'), { recursive: true });
copyFileSync(harmonyJs, join(out, 'harmony.js'));
const logoDir = join(dsDir, 'assets', 'logo');
for (const f of readdirSync(logoDir).filter((f) => f.endsWith('.svg'))) copyFileSync(join(logoDir, f), join(out, 'logo', f));

// Extract `var ICONS = { ... };` without executing the runtime.
const src = readFileSync(harmonyJs, 'utf8');
const start = src.indexOf('var ICONS = {');
if (start < 0) throw new Error('ICONS object not found in harmony.js');
let depth = 0, i = src.indexOf('{', start), end = -1, quote = null;
for (; i < src.length; i++) {
  const c = src[i];
  if (quote) { if (c === '\\') { i++; continue; } if (c === quote) quote = null; continue; }
  if (c === "'" || c === '"' || c === '`') { quote = c; continue; }
  if (c === '{') depth++;
  else if (c === '}') { depth--; if (depth === 0) { end = i + 1; break; } }
}
if (end < 0) throw new Error('could not find the end of ICONS');
const icons = vm.runInNewContext('(' + src.slice(src.indexOf('{', start), end) + ')');
const names = Object.keys(icons);

mkdirSync(join(root, 'lib', 'ui'), { recursive: true });
writeFileSync(
  join(root, 'lib', 'ui', 'icons.generated.ts'),
  '// Generated by scripts/copy-design-system.mjs from ergos-harmony/harmony.js. Do not edit.\n' +
    'export const ICONS: Record<string, string> = ' + JSON.stringify(icons, null, 2) + ';\n' +
    'export type IconName = ' + names.map((n) => JSON.stringify(n)).join(' | ') + ';\n',
);
console.log(`ergos-harmony: copied harmony.js and ${readdirSync(join(out, 'logo')).length} logos, generated ${names.length} icons`);
